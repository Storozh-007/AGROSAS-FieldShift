#!/usr/bin/env python3
"""Gateway adapter: newline-delimited real sensor JSON -> authenticated telemetry API.
Example: export AGROSAS_API_URL=http://127.0.0.1:8000; export APP_TOKEN=...
Send lines with device_id, metric, value, unit and optional ISO timestamp.
No demonstration values or credentials are generated by this adapter.
"""
import json
import os
import sys
import httpx

def main():
    base=os.environ.get('AGROSAS_API_URL','http://127.0.0.1:8000').rstrip('/')
    token=os.environ.get('APP_TOKEN')
    if not token:raise SystemExit('Set APP_TOKEN in the trusted gateway environment')
    with httpx.Client(timeout=15,headers={'Authorization':f'Bearer {token}'}) as client:
        for line in sys.stdin:
            if not line.strip():continue
            try:
                data=json.loads(line)
                if not all(k in data for k in ['device_id','metric','value']):raise ValueError('device_id, metric and value are required')
                response=client.post(f'{base}/api/telemetry',json=data)
                response.raise_for_status()
                print(json.dumps({'status':'accepted','measurement_id':response.json()['measurement_id']}),flush=True)
            except (ValueError,httpx.HTTPError) as exc:
                print(json.dumps({'status':'rejected','reason':str(exc)}),file=sys.stderr,flush=True)
if __name__=='__main__':main()
